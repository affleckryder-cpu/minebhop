"""Generates a datapack that builds a race track for the vanilla-vs-bhop videos.

    python gallery/make_track.py "<world folder>"

In game: stand where the start line should be, face the way the track should run, and run
    /function racetrack:build
It snaps to the nearest compass direction, clears a corridor through the terrain and builds
the track about two seconds later (the far end has to load first).
    /function racetrack:start      teleports you back to the start line, facing down the track

The layout is the SECTIONS list below, in track coordinates: f = blocks forward from the start
line, r = blocks right of the centre line, u = blocks above the floor you stand on.
"""
import json
import os
import sys

HALF_WIDTH = 3                # the running surface is r = -3..3, seven blocks wide
LENGTH = 214                  # f of the finish wall

# Every obstacle is passable by vanilla sprint-jumping too, or it would not be a race:
# pits are at most 4 wide and 1 deep, walls leave a 3-block gap, steps rise 1 block at a time.
PITS = [(52, 54), (63, 65), (74, 77), (86, 89)]                 # first..last f of each gap
SLALOM = [(106, -3, 0), (118, 0, 3), (130, -3, 0), (142, 0, 3), (154, -3, 0)]   # f, r from, r to
STEPS = [(164, 171, 1), (172, 179, 2), (180, 187, 1)]           # first f, last f, height


def commands():
    """The track as (kind, ...) tuples in track coordinates."""
    out = []

    def fill(f1, r1, u1, f2, r2, u2, block):
        out.append((f1, r1, u1, f2, r2, u2, block))

    back, front = -4, LENGTH + 4
    # A corridor through whatever terrain is in the way, in pieces small enough for /fill.
    for f in range(back, front + 1, 40):
        end = min(f + 39, front)
        fill(f, -7, 0, end, 7, 9, "air")
        fill(f, -5, -3, end, 5, -2, "dirt")                     # so it does not hang over valleys as a sheet
        fill(f, -5, -1, end, 5, -1, "black_concrete")           # the border strips
        fill(f, -HALF_WIDTH, -1, end, HALF_WIDTH, -1, "grass_block")

    fill(0, -HALF_WIDTH, -1, 0, HALF_WIDTH, -1, "gold_block")   # start line

    for first, last in PITS:
        fill(first, -HALF_WIDTH, -1, last, HALF_WIDTH, -1, "air")
        fill(first, -HALF_WIDTH, -2, last, HALF_WIDTH, -2, "orange_concrete")
        fill(first - 1, -HALF_WIDTH, -1, first - 1, HALF_WIDTH, -1, "yellow_concrete")
        fill(last + 1, -HALF_WIDTH, -1, last + 1, HALF_WIDTH, -1, "yellow_concrete")

    for f, r1, r2 in SLALOM:
        fill(f, r1, 0, f, r2, 2, "red_concrete")                # three high: go round, not over

    for first, last, height in STEPS:
        fill(first, -HALF_WIDTH, 0, last, HALF_WIDTH, height - 1, "light_blue_concrete")

    fill(LENGTH - 4, -HALF_WIDTH, -1, LENGTH - 4, HALF_WIDTH, -1, "gold_block")     # finish line
    fill(LENGTH, -5, 0, LENGTH, 5, 6, "black_concrete")                             # finish wall
    return out


# Track coordinates -> world offsets, per compass direction: (dx, dz) for one step forward and
# one step right, and the yaw a player faces when looking down the track.
DIRECTIONS = {
    "south": ((0, 1), (-1, 0), 0),
    "west": ((-1, 0), (0, -1), 90),
    "north": ((0, -1), (1, 0), 180),
    "east": ((1, 0), (0, 1), -90),
}


def rel(n):
    return "~%d" % n if n else "~"


def world(direction, f, r, u):
    (fx, fz), (rx, rz), _ = DIRECTIONS[direction]
    return "%s %s %s" % (rel(f * fx + r * rx), rel(u), rel(f * fz + r * rz))


def direction_function(direction):
    lines = ["# Generated by gallery/make_track.py. Runs at the start marker."]
    for f1, r1, u1, f2, r2, u2, block in commands():
        lines.append("fill %s %s %s" % (world(direction, f1, r1, u1), world(direction, f2, r2, u2), block))
    lines.append(forceload(direction, "remove"))
    lines.append('tellraw @a [{"text":"[Racetrack] ","color":"aqua"},{"text":"Built. /function racetrack:start takes you to the start line.","color":"white"}]')
    return "\n".join(lines) + "\n"


def forceload(direction, action):
    (fx, fz), (rx, rz), _ = DIRECTIONS[direction]
    corners = [(f * fx + r * rx, f * fz + r * rz) for f in (-6, LENGTH + 6) for r in (-8, 8)]
    xs, zs = [c[0] for c in corners], [c[1] for c in corners]
    return "forceload %s %s %s %s %s" % (action, rel(min(xs)), rel(min(zs)), rel(max(xs)), rel(max(zs)))


def place_function(direction):
    yaw = DIRECTIONS[direction][2]
    return "\n".join([
        "# Marks the start, loads the area the track will cover, and builds it once that has loaded.",
        "kill @e[type=minecraft:marker,tag=rt_start]",
        'execute align xyz positioned ~0.5 ~ ~0.5 run summon minecraft:marker ~ ~ ~ {Tags:["rt_start","rt_build","rt_%s"],Rotation:[%df,0f]}' % (direction, yaw),
        "execute align xyz positioned ~0.5 ~ ~0.5 run " + forceload(direction, "add"),
        "schedule function racetrack:run 40t",
        'tellraw @s [{"text":"[Racetrack] ","color":"aqua"},{"text":"Building %d blocks to the %s...","color":"white"}]' % (LENGTH, direction),
    ]) + "\n"


def write(world_folder):
    root = os.path.join(world_folder, "datapacks", "racetrack")
    functions = os.path.join(root, "data", "racetrack", "function")
    os.makedirs(functions, exist_ok=True)
    with open(os.path.join(root, "pack.mcmeta"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({"pack": {"description": "MineBhop race track builder", "min_format": 107, "max_format": 107}}, f, indent=2)

    files = {
        # Which way the player faces picks the direction; north straddles the +-180 wrap.
        "build": "\n".join([
            "execute if entity @s[y_rotation=-45..45] run function racetrack:place_south",
            "execute if entity @s[y_rotation=45..135] run function racetrack:place_west",
            "execute if entity @s[y_rotation=135..180] run function racetrack:place_north",
            "execute if entity @s[y_rotation=-180..-135] run function racetrack:place_north",
            "execute if entity @s[y_rotation=-135..-45] run function racetrack:place_east",
        ]) + "\n",
        "run": "\n".join(
            ["execute as @e[type=minecraft:marker,tag=rt_build,tag=rt_%s] at @s run function racetrack:%s" % (d, d) for d in DIRECTIONS]
            + ["tag @e[type=minecraft:marker,tag=rt_build] remove rt_build"]) + "\n",
        "start": "\n".join([
            "# The marker carries the track's yaw, so teleporting to it also faces you down the track.",
            "tp @s @e[type=minecraft:marker,tag=rt_start,limit=1]",
        ]) + "\n",
    }
    for direction in DIRECTIONS:
        files[direction] = direction_function(direction)
        files["place_" + direction] = place_function(direction)
    for name, text in files.items():
        with open(os.path.join(functions, name + ".mcfunction"), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote %d functions to %s" % (len(files), root))
    print("%d fill commands per direction, largest %d blocks" % (
        len(commands()), max((abs(c[3] - c[0]) + 1) * (abs(c[4] - c[1]) + 1) * (abs(c[5] - c[2]) + 1) for c in commands())))


if __name__ == "__main__":
    write(sys.argv[1])
